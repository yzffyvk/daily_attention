function lesson(sequence: number, topic: Topic, content: LessonContent): TakeawayLesson {
  return {
    id: `tennis-${String(sequence).padStart(2, "0")}`,
    sequence,
    domain: "tennis",
    topic,
    ...content,
    readingSeconds: 60,
    version: 1,
    correctionNote: null,
    sourceVerifiedAt: "2026-10-09",
  };
}

